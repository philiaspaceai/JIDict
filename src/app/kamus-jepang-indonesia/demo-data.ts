/** Cari di data demo: kanji/kana/romaji/arti. Maks 8 hasil. */
export function filterDemo(rawQuery: string, limit = 8): DemoEntry[] {
  const q = normalizeQuery(rawQuery);
  if (!q) return [];
  const qLow = q.toLowerCase();
  return DEMO_ENTRIES.filter(
    (e) =>
      e.expression.includes(q) ||
      e.reading.includes(q) ||
      e.gloss.toLowerCase().includes(qLow),
  ).slice(0, limit);
}
